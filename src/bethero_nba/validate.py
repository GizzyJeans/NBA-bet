def _f(x: float, digits: int = 4) -> str:
    return f"{x:.{digits}f}"


def _seasons(seasons) -> str:
    seasons = list(seasons)
    return f"{seasons[0]} to {seasons[-1]} ({len(seasons)} seasons)" if len(seasons) > 2 else ", ".join(seasons)


